/* ============================================
   USER LOGIN
   ============================================ */

/**
 * @swagger
 * /api/auth/user/login:
 *   post:
 *     summary: User login (Assistant/Teacher/Super Admin)
 *     description: Login for assistants, teachers, and super admins using phone and password
 *     tags: [Auth]
 *     security:
 *       - ApiAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [phone, password]
 *             properties:
 *               phone:
 *                 type: string
 *                 description: User phone number (unique)
 *                 example: "01012345678"
 *               password:
 *                 type: string
 *                 description: User password (min 4 characters)
 *                 example: "123456"
 *     responses:
 *       200:
 *         description: Login successful
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 message:
 *                   type: string
 *                   example: "تم تسجيل الدخول بنجاح!"
 *                 token:
 *                   type: string
 *                   description: JWT token for authentication
 *                 user:
 *                   type: object
 *                   properties:
 *                     id:
 *                       type: integer
 *                     role:
 *                       type: string
 *                       enum: [super_admin, assistant, teacher]
 *                     permissions:
 *                       type: string
 *                       enum: [online_management, center_management]
 *                     full_name:
 *                       type: string
 *                     phone:
 *                       type: string
 *                     profile_image:
 *                       type: string
 *       400:
 *         description: Validation error
 *       401:
 *         description: Invalid credentials
 */

/* ============================================
   STUDENT LOGIN
   ============================================ */

/**
 * @swagger
 * /api/auth/student/login:
 *   post:
 *     summary: Student login
 *     description: Login for students using phone (or parent phone) and password
 *     tags: [Auth]
 *     security:
 *       - ApiAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [phone, password]
 *             properties:
 *               phone:
 *                 type: string
 *                 description: Student phone or parent phone
 *                 example: "01012345678"
 *               password:
 *                 type: string
 *                 description: Student password (generated by admin)
 *                 example: "STU-2024-001@jupiter.com"
 *     responses:
 *       200:
 *         description: Login successful
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 message:
 *                   type: string
 *                   example: "تم تسجيل الدخول بنجاح!"
 *                 token:
 *                   type: string
 *                   description: JWT token for authentication
 *                 student:
 *                   type: object
 *                   properties:
 *                     id:
 *                       type: integer
 *                     barcode:
 *                       type: string
 *                     role:
 *                       type: string
 *                       example: "student"
 *                     full_name:
 *                       type: string
 *                     phone:
 *                       type: string
 *                     grade_id:
 *                       type: integer
 *                     group_id:
 *                       type: integer
 *                     profile_image:
 *                       type: string
 *       400:
 *         description: Validation error
 *       401:
 *         description: Invalid credentials or no password set
 */

